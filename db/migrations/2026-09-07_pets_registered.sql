-- 강아지에게 **동물등록 여부** 한 칸을 더한다.
-- db/init/05_pets.sql 과 같은 결과가 되게 한다.
--
-- **여러 번 돌려도 안전하다.** 이 저장소는 버전 테이블이 없어서 DB 가 적용 여부를
-- 기억하지 않는다 — db/migrations/README.md 참고.
--
-- 왜: `docs/life/roadmap.md` §3-F 의 `F5`(일정·알림)가 이 칸을 기다린다. 동물보호법
-- 제15조의 동물등록을 했는지에 따라 알릴 말이 갈린다 — 안 한 사람에게는 "등록하세요",
-- 한 사람에게는 "정보가 바뀌면 30일 안에 변경신고" 다. 지금은 그 값이 아예 없어서
-- 어느 쪽 말도 못 한다.
--
-- **컬럼만 먼저 나간다.** 앱 입력 화면과 알림은 뒤 카드이고, 읽는 코드는 아직 없다.
-- 오늘 GCP 스냅샷에 태우려고 먼저 낸다 — 나중에 하면 손으로 하는 왕복이 한 번 는다.

BEGIN;

ALTER TABLE pets ADD COLUMN IF NOT EXISTS registered BOOLEAN;

COMMENT ON COLUMN pets.registered IS
    '동물등록(동물보호법 제15조) 여부. NULL 은 ''모름''이고 모름을 false 로 바꾸지 않는다';

-- ⚠ **기본값을 걸지 않는다. 이것이 이 마이그레이션에서 제일 중요한 줄이다.**
--
-- `DEFAULT false` 를 걸면 안 물어본 강아지가 전부 "등록 안 했다"가 된다. 그러면 F5 가
-- 그 사람들에게 "등록하세요" 를 보내는데, 실제로는 이미 등록했을 수 있다. 옆 칸
-- `neutered`·`sex` 가 같은 이유로 기본값 없이 NULL 을 쓴다 (db/init/05_pets.sql).
--
-- 이미 있는 행도 그래서 안 채운다 — 백필할 정답이 없다.
-- `verify_2026-09-07_pets_registered.sql` 이 **기본값이 없는지를 단언**한다.

COMMIT;
