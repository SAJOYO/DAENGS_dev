"""질의의 지자체 신호 → 검색에서 **남길** `org` 목록 (RAG-063).

`transport` 와 같은 자리에 있는 모듈이다 — **질의의 낱말**을 문서 쪽에 이미 있는 값 사전과
잇는다. 다른 점은 방향이다: 교통은 *배제*하고 지역은 *남긴다*. 이유는 아래 "왜 남기기인가".

────────────────────────────────────────────────────────────────────────────
왜 이 축이 필요한가 — S3 가 13랩 연속 실패했다
────────────────────────────────────────────────────────────────────────────
RAG-033 ⑥ 이 *"우리 동네 질문이 이 도메인의 존재 이유인데 정확히 그 축이 약하다"* 고 적고
셋(ⓐ `org` 사전필터 · ⓑ 하이브리드/BM25 · ⓒ 되묻기) 중 못 골라 미룬 자리다. 그중 **ⓑ 는 그 뒤
RAG-035 로 실제로 들어왔고, S3(부산 동래구)는 lap10부터 13랩 연속 실패다.** `D5`(RAG-057)는
순위 상수로도 못 고침을 증명했다 — S3 는 `w≥1.35` 를 요구하는데 DP1 은 `w≤0.20` 을 요구해
전역 상수로는 동시에 만족할 수 없다. 그래서 남은 것이 ⓐ 다.

────────────────────────────────────────────────────────────────────────────
`org` 을 원본으로 삼는다 — `document_title` 을 파싱하지 않는다
────────────────────────────────────────────────────────────────────────────
RAG-033 ⑥ 은 *"조례명 띄어쓰기가 지자체마다 제각각이라(`부산광역시동래구` 붙음 /
`서울특별시 성동구` 띄움) 질의 표기를 맞추는 방식으로는 못 덮는다"* 고 못 박았다. 그 진단은
**조례명에 대해서는 맞고 `org` 에 대해서는 틀리다** (2026-09-05 실측):

    org  = "부산광역시 동래구"          ← 공백이 정상적으로 들어 있다
    title= "부산광역시동래구 반려동물…"   ← 붙어 있다

`org` 은 법제처가 `지자체기관명` 으로 주는 값이라 이미 정규화돼 있다. 그래서 이 모듈은
**`org` 만 보고 제목은 절대 파싱하지 않는다** — 제목에서 지자체명을 다시 뽑으면 같은 사실의
두 번째 진실이 생기고, 그것이 RAG-042 ③ 이 `BY_SOURCE` 에서 지적한 병이다.

────────────────────────────────────────────────────────────────────────────
왜 "배제"가 아니라 "남기기"인가 — 그리고 왜 `org` 없는 문서는 안 건드리는가
────────────────────────────────────────────────────────────────────────────
"부산 동래구에서 목줄 안 하면 과태료?" 의 답은 **조례가 아니라 동물보호법**에 있고, 법령에는
`org` 이 없다. 지역 신호가 있다고 `org` 이 없는 문서를 빼면 **고치려던 것보다 큰 것이 사라진다**
(`transport` 가 "남기기"를 고른 순간 easylaw 청크가 통째로 빠지던 것과 같은 함정이다).

그래서 필터는 **`org` 이 없거나(=전국 공통) 신호와 맞는 것**만 남긴다. 실제로 걸러지는 것은
*다른 지자체의 조례·보조금* 뿐이고, 그것이 S3 의 top-8 을 채우고 있던 바로 그 문서들이다.

규칙 넷 (`orgs`):
    1. **광역 + 기초가 다 적혀 있으면** 그 조합 하나로 좁힌다 ("부산 동래구")
    2. **기초만 적혀 있으면** 그 이름을 가진 지자체를 **전부** 남긴다 — `고성군` 은 강원·경남에
       둘 다 있고 `남구` 는 다섯 곳에 있다. 하나를 고르면 틀릴 때 조용히 틀린다
    3. **광역만 적혀 있으면** 그 광역과 **그 안의 기초 전부**를 남긴다. 지원 조례는 기초가
       만들기 때문이다 — RAG-033 이 *"135곳 중 광역은 34건(16%)뿐"* 이라고 실측한 자리다
    4. **신호가 없으면 아무것도 안 한다.** 지역을 안 밝힌 질의는 전국을 봐야 한다

사전은 코퍼스의 `org` 값에서 만든다 — 표를 손으로 적지 않는다 (RAG-042 ③).

────────────────────────────────────────────────────────────────────────────
부분 문자열이 아니라 **형태소 토큰**으로 맞춘다 — `고양이` 가 그 이유다
────────────────────────────────────────────────────────────────────────────
`transport` 는 부분 일치로 낱말을 찾는다(`항공사` 안의 `항공`). 지역에서 같은 것을 하면
**반려동물 도메인에서 가장 흔한 낱말 하나가 바로 터진다**:

    "주인을 잃고 배회하는 고양이를 발견했는데요"   ← 골든셋 QA7
                          ~~~~
    `고양` 이 경기도 **고양시**로 잡혀 질의가 고양시 문서로 좁혀진다.

`transport` 의 머리말이 *"오탐 가능성이 있는 관용구는 본 적이 없어 막지 않는다. 막을 일이
생기면 여기 적을 것"* 이라고 남겼는데, **이 카드가 그 일이 생긴 자리다.**

그래서 질의를 `core.tokenize` 로 잘라 **토큰과 정확히 같을 때만** 맞는 것으로 본다. Kiwi 가
`고양이를 → 고양이` 로, `부산에서 → 부산` 으로, `동래구는 → 동래구` 로 잘라 주므로 조사는
저절로 떨어지고 `고양이` 는 `고양` 과 다른 토큰이 된다. 렉시컬 검색이 쓰는 그 토크나이저다.
"""
from __future__ import annotations

import re

from . import tokenize

# 광역 축약형 → 정식 명칭의 앞머리. 사용자는 "충남"이라 치고 코퍼스에는 "충청남도"가 있다.
# **접미사 규칙으로는 못 덮는 자리다** — `충청남도`에서 `충남`은 규칙적으로 안 나온다.
WIDE_ALIASES: dict[str, str] = {
    "서울": "서울특별시", "부산": "부산광역시", "대구": "대구광역시", "인천": "인천광역시",
    "광주": "광주광역시", "대전": "대전광역시", "울산": "울산광역시", "세종": "세종특별자치시",
    "경기": "경기도", "강원": "강원특별자치도", "제주": "제주특별자치도",
    "충북": "충청북도", "충남": "충청남도", "전북": "전북특별자치도", "전남": "전라남도",
    "경북": "경상북도", "경남": "경상남도",
}

# 코퍼스에 실재하는 흔들림. **접두사 `(구)` 는 법제처가 폐지·통합된 기관에 붙인다.**
# `전남광주통합특별시` 는 통합 명칭이고, 사용자는 어느 쪽이든 그냥 "광주"라고 친다.
_LEGACY_PREFIX = re.compile(r"^\(구\)\s*")
_WIDE_SUFFIX = re.compile(r"(특별시|광역시|특별자치시|특별자치도|도)$")
_LOCAL_SUFFIX = re.compile(r"(시|군|구)$")


def split_org(org: str) -> tuple[str, str | None]:
    """`org` 한 줄 → (광역, 기초). 기초가 없으면 `(광역, None)`.

    `(구)` 접두사는 떼고 본다 — `(구)광주광역시` 와 `광주광역시` 는 사용자에게 같은 곳이다.
    """
    cleaned = _LEGACY_PREFIX.sub("", org).strip()
    parts = cleaned.split()
    if len(parts) >= 2:
        return parts[0], " ".join(parts[1:])
    return cleaned, None


def _wide_keys(wide: str) -> set[str]:
    """광역 하나가 질의에서 불릴 수 있는 이름들."""
    keys = {wide}
    bare = _WIDE_SUFFIX.sub("", wide)
    if bare:
        keys.add(bare)
    for alias, full in WIDE_ALIASES.items():
        # `full == wide` 가 정상 경로다. `alias in wide` 는 **통합·개칭된 이름**을 위한 것으로,
        # 코퍼스에 실재하는 `전남광주통합특별시` 가 그 자리다 — 사용자는 "광주"라고도 "전남"
        # 이라고도 치고, 통합 명칭이니 **둘 다 맞다.** `startswith` 로 하면 "광주"를 놓친다.
        if full == wide or alias in wide:
            keys.add(alias)
    return {k for k in keys if len(k) >= 2}


def _local_keys(local: str) -> set[str]:
    """기초 하나가 질의에서 불릴 수 있는 이름들. `동래구` 와 `동래` 를 둘 다 잡는다."""
    keys = {local}
    bare = _LOCAL_SUFFIX.sub("", local)
    if len(bare) >= 2:
        keys.add(bare)
    return keys


def orgs(text: str, known: list[str]) -> tuple[str, ...]:
    """질의에서 읽은 지역 → **남길 `org` 목록.** 신호가 없으면 빈 튜플.

    `known` 은 코퍼스에 실재하는 `org` 값 전부다. 호출부가 흘려 넣는다 — 이 모듈은 DB 를
    모르는 채로 남는다 (`transport` 가 그런 것처럼, 그리고 `score` 가 그런 것처럼).
    """
    if not text or not known:
        return ()

    # **토큰 집합과의 정확 일치다** (위 머리말 — `고양이`/`고양시`). 부분 문자열이 아니다.
    seen = set(tokenize.tokens(text))
    if not seen:
        return ()

    wide_hits: set[str] = set()
    local_hits: set[str] = set()
    for org in known:
        wide, local = split_org(org)
        if _wide_keys(wide) & seen:
            wide_hits.add(wide)
        if local and _local_keys(local) & seen:
            local_hits.add(local)

    if not wide_hits and not local_hits:
        return ()

    keep: set[str] = set()
    for org in known:
        wide, local = split_org(org)
        if wide_hits and local_hits:
            # 규칙 1 — 조합이 맞는 것만. 광역 자신(`local is None`)은 광역이 맞으면 남긴다
            if wide in wide_hits and (local in local_hits or local is None):
                keep.add(org)
        elif local_hits:
            # 규칙 2 — 이름이 같은 기초를 전부
            if local in local_hits:
                keep.add(org)
        else:
            # 규칙 3 — 광역과 그 안의 기초 전부
            if wide in wide_hits:
                keep.add(org)
    return tuple(sorted(keep))
