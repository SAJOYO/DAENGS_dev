"""질의의 일상어 → 조문이 쓰는 낱말 (RAG-066).

`region` · `transport` 와 같은 자리에 있는 모듈이다 — **질의의 낱말을 읽어** 검색을 돕는다.
다른 점은 **무엇을 만드느냐**다:

    transport   질의를 읽고 → SQL 에서 뺄 subcategory 를 고른다
    region      질의를 읽고 → SQL 에서 남길 org 을 고른다
    vocabulary  질의를 읽고 → **질의 문장 자체를 넓힌다**   ← 이 모듈

────────────────────────────────────────────────────────────────────────────
왜 필요한가 — 겹치는 낱말이 하나도 없다
────────────────────────────────────────────────────────────────────────────
    사용자가 친 것: "아파트에서 반려견을 키우려면 관리사무소 동의를 받아야 하나요"
    정답 조문    : "가축(장애인 보조견은 제외한다)을 사육하거나 … 공동주거생활에 피해를
                   미치는 행위"        (공동주택관리법 시행령 제19조제2항제4호)

**한 낱말도 안 겹친다.** 문서도 임베딩도 순위 공식도 멀쩡한데 어휘만 안 맞아 top-10 밖이다.
법률 어휘로 다시 물으면 **1위**로 온다. `#268`(RAG-065 ⑨)이 `HS1` 을 실패로 남기며 이 자리를
열었고, 정찰에서 같은 병이 셋으로 확인됐다 (`tools/d11_vocabulary_probe.py`).

────────────────────────────────────────────────────────────────────────────
왜 **다시 인코딩**해야 하는가 — 렉시컬만 넓히면 안 된다
────────────────────────────────────────────────────────────────────────────
`tokenize.tsquery` 는 토큰 OR 이라 별칭을 더하기가 제일 쉽다. 그런데 정찰 실측(2026-09-06):

    HS1  아파트 반려견 동의   지금 없음 · 렉시컬만 **없음** · 다시 인코딩 **1위**
    FW3  동물 화장장         지금 없음 · 렉시컬만  7위   · 다시 인코딩 **1위**
    DP1  비행기 태우기       지금  6위 · 렉시컬만  3위   · 다시 인코딩 **2위**

**dense 가 후보를 정하기 때문에 렉시컬만으로는 `HS1` 이 아예 안 온다.** 그래서 확장은 질의
텍스트에 걸고 다시 인코딩해야 하고, 그것이 이 모듈이 `search()` **안**에 못 사는 이유다 —
벡터는 `search()` 에 들어오기 전에 이미 만들어져 있다. `search.encode()` 가 유일한 입구가 되어
그 안에서 이 모듈을 부른다.

────────────────────────────────────────────────────────────────────────────
부분 문자열이 아니라 **형태소 토큰**으로 맞춘다
────────────────────────────────────────────────────────────────────────────
`region` 이 `고양이`/`고양시` 로 배운 것을 그대로 따른다 (RAG-063). 부분 일치로 하면
`관리사무소` 를 찾으려다 `관리` 가 든 모든 질의에 붙는다.

────────────────────────────────────────────────────────────────────────────
사전을 늘리는 규칙 — **정찰이 값을 보인 쌍만 넣는다**
────────────────────────────────────────────────────────────────────────────
별칭 사전은 무한히 자라는 종류의 파일이고 **오탐이 조용하다** — 엉뚱한 낱말이 붙은 질의는
예외가 안 나고 그냥 답이 나빠질 뿐이다. 그래서 규칙을 하나 둔다:

    `tools/d11_vocabulary_probe.py` 가 "이 별칭이 이 문항을 살린다"를 보인 쌍만 넣는다.

짐작으로 넣지 않는다. 아래 표의 오른쪽 열이 그 증거다.
"""
from __future__ import annotations

from typing import NamedTuple

from . import tokenize


class Alias(NamedTuple):
    """트리거 하나가 더할 낱말들과, 그것이 걸리기 위한 **맥락 조건**.

    `requires` 가 있으면 그중 하나가 질의에 **같이** 있어야 한다. 없으면 무조건 건다.
    """
    add: tuple[str, ...]
    requires: tuple[str, ...] = ()


# 주거 맥락. `가축` 을 여는 열쇠다 — 아래 ⚠ 참고.
_HOUSING = ("아파트", "공동주택", "관리사무소", "관리주체", "입주민", "입주자", "단지", "층간소음")

# 질의에 이 낱말(형태소 토큰)이 있으면 → 오른쪽 낱말들을 질의에 더한다.
#
# **한 방향이다.** 조문 어휘로 물은 질의는 이미 잘 찾으므로 되돌릴 이유가 없고, 양방향으로 두면
# 조문 어휘가 일상어를 끌어와 검색이 넓어지기만 한다.
ALIASES: dict[str, Alias] = {
    # ---- 주거 (F4-ⓐ / HS1: 없음 → 1위)
    "아파트": Alias(("공동주택",)),
    "관리사무소": Alias(("관리주체",)),
    "입주민": Alias(("입주자",)),
    # ⚠ **`반려동물` → `가축` 은 주거 맥락에서만 건다.**
    #
    # 이 별칭이 필요한 이유는 **공동주택관리법 시행령 제19조제2항제4호**가 반려동물을 `가축`
    # 이라고 부르기 때문이고, 그 한 호가 F4-ⓐ 를 들인 이유 전부다 (RAG-065 ④).
    #
    # 그런데 조건 없이 걸면 **골든셋 46문항 중 18개가 확장되고 그중 대부분이 이 한 줄 때문**
    # 이었다 (2026-09-06 실측). 조례 지원금(S1·S4·S5)·기차(T2·T3·T5)·해설(QA*)까지 `가축` 이
    # 붙는데, 코퍼스에는 **가축전염병예방법**이 통째로 들어 있어 검색이 그쪽으로 끌려간다.
    # `반려동물` 은 이 도메인에서 가장 흔한 낱말이라 사정거리가 곧 코퍼스 전체다.
    #
    # 맥락을 걸면 18 → 6 으로 줄고, 줄어든 12개는 전부 `가축` 과 무관한 문항이다.
    "반려견": Alias(("가축",), requires=_HOUSING),
    "반려동물": Alias(("가축",), requires=_HOUSING),
    "강아지": Alias(("가축",), requires=_HOUSING),
    # ---- 장례 (FW3: 없음 → 1위). 사람은 "화장장", 법은 "장묘시설"이라 쓴다.
    # RAG-059 는 이 실패를 *"조례가 top-5 를 차지해 제72조가 안 온다"* 로 적고 진짜 실패로
    # 남겼는데, **조례가 이긴 이유**가 이것이었다. 순위 문제로 보이던 것이 어휘 문제였다.
    #
    # `화장장` 은 그 자체로 한 토큰이라 조건이 필요 없다. **맨 `화장` 은 안 넣는다** —
    # `화장실`·`화장품` 은 형태소가 달라 안 걸리지만, 화장(化粧) 자체를 묻는 질의가 언제든
    # 생길 수 있고 그 오탐은 조용하다. 지금 값을 보인 것은 `화장장` 뿐이다.
    "화장장": Alias(("동물장묘시설", "장묘업")),
    # ---- 항공 (DP1: 6위 → 2위)
    "비행기": Alias(("항공", "기내", "운송")),
}


def aliases(text: str) -> tuple[str, ...]:
    """질의에서 읽은 별칭. 신호가 없으면 빈 튜플.

    **토큰 집합과의 정확 일치다** (위 머리말). 이미 질의에 있는 낱말은 안 더한다 — 같은 낱말을
    두 번 넣으면 렉시컬 축의 가중치만 흔들리고 얻는 것이 없다.
    """
    if not text:
        return ()
    seen = set(tokenize.tokens(text))
    if not seen:
        return ()
    out: list[str] = []
    for trigger, alias in ALIASES.items():
        if trigger not in seen:
            continue
        if alias.requires and not (set(alias.requires) & seen):
            continue
        out += [w for w in alias.add if w not in seen and w not in out]
    return tuple(out)


def expand(text: str) -> str:
    """질의 문장 + 별칭. 신호가 없으면 **원문 그대로** 돌려준다.

    ⚠ **이 결과를 `Query.text` 에 넣지 않는다.** `transport.exclusions()` 와 `region.orgs()` 가
    `query.text` 를 읽는데, 넓힌 문장을 거기 넣으면 교통·지역 신호가 오작동한다 — 예를 들어
    `비행기` → `운송` 이 더해지면 교통 배제가 엉뚱하게 켜진다. **인코딩에만 쓰고 원문은 남긴다.**
    """
    found = aliases(text)
    return f"{text} {' '.join(found)}" if found else text
