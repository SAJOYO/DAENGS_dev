-- !! 주의 !!
-- 이 파일은 docker-entrypoint-initdb.d 에 넣지 말 것.
-- 데이터 적재가 끝난 뒤에 수동으로 실행한다.
--
-- 이유: 벡터 인덱스를 빈 테이블에 미리 만들면
--       - 행이 들어올 때마다 그래프를 갱신하느라 INSERT가 느려지고
--       - IVFFlat의 경우 클러스터 학습이 불가능해 품질이 망가진다.
--       일반 B-tree/GIN도 대량 적재 시에는 나중에 만드는 편이 빠르다.
--
-- 실행 방법 예시:
--   docker compose exec -T pgvector psql -U postgres -d vectordb < db/indexes.sql
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1) 벡터 유사도 검색 (HNSW)
--    vector_cosine_ops 로 만들었으므로 쿼리도 코사인 연산자 <=> 로 통일할 것.
--    다른 연산자(<->, <#>)를 쓰면 인덱스를 타지 않는다.
-- ---------------------------------------------------------------------
CREATE INDEX idx_documents_embedding ON documents
    USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);


-- ---------------------------------------------------------------------
-- 2) 카테고리 필터링 (메타데이터 기반 사전 필터)
-- ---------------------------------------------------------------------
CREATE INDEX idx_documents_cat ON documents (category, subcategory);


-- ---------------------------------------------------------------------
-- 3) JSONB 조회
-- ---------------------------------------------------------------------
CREATE INDEX idx_documents_meta ON documents USING gin (metadata);


